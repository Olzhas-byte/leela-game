// ── Производные структуры для быстрого доступа ───────────────────────────────

const CELL_BY_NUMBER = new Map<number, Cell>(CELLS.map((c) => [c.number, c]));
const TRANSITION_BY_FROM = new Map<number, Transition>(
  TRANSITIONS.map((t) => [t.from, t]),
);

export function getCell(n: number): Cell {
  const cell = CELL_BY_NUMBER.get(n);
  if (!cell) throw new Error(`Нет клетки с номером ${n}`);
  return cell;
}

export function getTransitionFrom(n: number): Transition | undefined {
  return TRANSITION_BY_FROM.get(n);
}

// ── Самопроверка целостности данных (выполняется при импорте в dev) ──────────

export function validateBoard(): void {
  if (CELLS.length !== BOARD_SIZE) {
    throw new Error(`Ожидалось ${BOARD_SIZE} клеток, получено ${CELLS.length}`);
  }
  for (let i = 1; i <= BOARD_SIZE; i++) {
    if (!CELL_BY_NUMBER.has(i)) throw new Error(`Пропущена клетка ${i}`);
  }
  for (const t of TRANSITIONS) {
    if (t.from < 1 || t.from > BOARD_SIZE || t.to < 1 || t.to > BOARD_SIZE) {
      throw new Error(`Переход вне диапазона: ${t.from}->${t.to}`);
    }
    if (t.type === 'arrow' && t.to <= t.from) {
      throw new Error(`Стрела должна вести вверх: ${t.from}->${t.to}`);
    }
    if (t.type === 'snake' && t.to >= t.from) {
      throw new Error(`Змея должна вести вниз: ${t.from}->${t.to}`);
    }
  }
  const froms = TRANSITIONS.map((t) => t.from);
  if (new Set(froms).size !== froms.length) {
    throw new Error('На одной клетке не может быть двух переходов');
  }
}
